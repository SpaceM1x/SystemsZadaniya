
# Варианты решений
options = {
    "Большой магазин": {
        "Благоприятный рынок": {"вероятность": 0.5, "результат": 60},
        "Неблагоприятный рынок": {"вероятность": 0.5, "результат": -40}
    },
    "Маленький магазин": {
        "Благоприятный рынок": {"вероятность": 0.5, "результат": 30},
        "Неблагоприятный рынок": {"вероятность": 0.5, "результат": -10}
    }
}

# Ожидаемая стоимостная ценность (EMV) для каждого варианта
emv_big = sum([event["вероятность"] * event["результат"] for event in options["Большой магазин"].values()])
emv_small = sum([event["вероятность"] * event["результат"] for event in options["Маленький магазин"].values()])

# Результаты
print(f"Ожидаемая ценность для большого магазина: {emv_big} млн руб.")
print(f"Ожидаемая ценность для маленького магазина: {emv_small} млн руб.")

# Оптимальное решение
best_option = "Большой магазин" if emv_big > emv_small else "Маленький магазин"
if emv_big == emv_small:
    conclusion = "Оба варианта имеют одинаковую ожидаемую ценность."
else:
    conclusion = f"Оптимальное решение: {best_option}"

print(conclusion)